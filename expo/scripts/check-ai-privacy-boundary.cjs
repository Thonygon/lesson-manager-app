const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = (name) => fs.readFileSync(path.join(__dirname, '..', name), 'utf8');
const provider = read('src/server/ai-provider-chain.ts');
const cover = read('src/app/api/lesson-plan-cover+api.ts');
const teacher = read('src/app/(app)/smart-tools.tsx');
const publicTool = read('src/components/public-smart-tool.tsx');
const resources = read('src/app/(app)/resources.tsx');
const notice = read('src/components/ai-data-notice.tsx');
const providerHosts = /api\.openai\.com|openrouter\.ai|generativelanguage\.googleapis\.com/;
const routeDir = path.join(__dirname, '../src/app/api');
const providerRoutes = fs.readdirSync(routeDir).filter((name) => name.endsWith('.ts') && providerHosts.test(read(`src/app/api/${name}`))).sort();
assert.deepEqual(providerRoutes, ['lesson-plan-cover+api.ts']);
assert.match(provider, /const providerPrompt = redactDirectIdentifiers\(userPrompt, knownStudentNames\)/);
assert.match(provider, /text: providerPrompt/);
assert.match(provider, /content: providerPrompt/);
assert.match(cover, /text: redactDirectIdentifiers\(prompt\)/);
assert.doesNotMatch(cover, /image_prompt: prompt/);
assert.match(teacher, /const \[notes, setNotes\] = useState\(''\)/);
assert.doesNotMatch(teacher, /student: params\.student/);
assert.match(teacher, /generateMaterial\(requestInput, setMessage, selectedStudentName, selectedStudentId\)/);
assert.match(read('src/app/api/generate+api.ts'), /body\.studentNameForRedaction \? \[text\(body\.studentNameForRedaction, 120\)\]/);
const smartToolsService = read('src/services/smart-tools.ts');
assert.doesNotMatch(smartToolsService.split('export type SmartToolInput =')[1].split(';')[0], /studentNameForRedaction/);
assert.doesNotMatch(smartToolsService.split('export type SmartToolInput =')[1].split(';')[0], /studentIdForEvidence/);
assert.match(smartToolsService, /body: JSON\.stringify\(\{ \.\.\.body, studentNameForRedaction, studentIdForEvidence \}\)/);
for (const screen of [teacher, publicTool, resources]) assert.match(screen, /<AiDataNotice/);
assert.match(notice, /smart\.aiRedactionLimit/);
assert.doesNotMatch(notice, /Pressable|accessibilityRole="checkbox"/);
process.stdout.write('AI provider privacy boundary and low-friction notices passed.\n');
