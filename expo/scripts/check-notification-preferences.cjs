const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/lib/notification-preferences.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const moduleRef = { exports: {} };
new Function('module', 'exports', 'require', code)(moduleRef, moduleRef.exports, require);
const { parseNotificationPreferences, notificationCategory } = moduleRef.exports;
assert.deepEqual(parseNotificationPreferences(null), { assignments: true, reviews: true, payments: true });
assert.deepEqual(parseNotificationPreferences('{"assignments":false,"reviews":true,"payments":false}'), { assignments: false, reviews: true, payments: false });
assert.deepEqual(parseNotificationPreferences('{"assignments":"false","reviews":null}'), { assignments: true, reviews: true, payments: true });
assert.deepEqual(parseNotificationPreferences('{bad json'), { assignments: true, reviews: true, payments: true });
assert.equal(notificationCategory('student:due:123'), 'assignments');
assert.equal(notificationCategory('student:graded:123'), 'assignments');
assert.equal(notificationCategory('student:review:123'), 'reviews');
assert.equal(notificationCategory('student:comment:123'), 'reviews');
assert.equal(notificationCategory('teacher:practice:123'), 'reviews');
assert.equal(notificationCategory('teacher:payment:123'), 'payments');
console.log('Notification preference fixtures passed');
